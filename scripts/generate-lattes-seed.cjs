// Generate the optional SQL import from the same data used by the admin preview.
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const sourcePath = path.resolve(__dirname, '../src/lib/lattes-content.ts');
const compiled = new Module(sourcePath, module);
compiled.filename = sourcePath;
compiled.paths = module.paths;
compiled._compile(ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText, sourcePath);
const { lattesProfile, lattesProjects, lattesPublications } = compiled.exports;
const literal = value => value == null ? 'null' : Array.isArray(value)
  ? `array[${value.map(literal).join(', ')}]::text[]` : typeof value === 'number' || typeof value === 'boolean'
    ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const starterProfile = {
  display_name: 'Erick Batista',
  biography: 'Estudante de Ciência da Computação na Universidade Federal de Rondônia. Desenvolvo projetos e exploro novas possibilidades em inteligência artificial, IoT e sistemas computacionais.',
  formation: 'Ciência da Computação — Universidade Federal de Rondônia',
  lattes_url: 'http://lattes.cnpq.br/1145013876792671',
};
const statements = [
  '-- Generated by node scripts/generate-lattes-seed.cjs. Do not edit this file by hand.',
  '-- Source: user-provided Lattes PDF updated on 2026-10-11, exported on 2026-10-21.',
  '-- Optional alternative to /admin/importar-lattes: run in the trusted Supabase SQL Editor.',
  '-- Run schema.sql first. New content is published. Existing records and custom profile fields are preserved.',
  'begin;',
];
const profile = Object.fromEntries(Object.entries(lattesProfile).filter(([, value]) => value != null));
const fields = Object.keys(profile);
statements.push(`insert into public.profile (${fields.join(', ')})\nvalues (${Object.values(profile).map(literal).join(', ')})\non conflict (id) do update set\n` + fields.filter(key => key !== 'id').map(key => {
  const column = `public.profile.${key}`;
  const starter = starterProfile[key] ? ` or ${column} = ${literal(starterProfile[key])}` : '';
  return `  ${key} = case when ${column} is null or btrim(${column}) = ''${starter} then excluded.${key} else ${column} end`;
}).join(',\n') + ';');
for (const item of lattesProjects) {
  const record = { ...item, published: true };
  statements.push(`insert into public.projects (${Object.keys(record).join(', ')})\nselect ${Object.values(record).map(literal).join(', ')}\nwhere not exists (select 1 from public.projects where slug = ${literal(item.slug)} or lower(btrim(title)) = lower(btrim(${literal(item.title)})))\non conflict (slug) do nothing;`);
}
for (const item of lattesPublications) {
  const record = { ...item, published: true };
  statements.push(`insert into public.publications (${Object.keys(record).join(', ')})\nselect ${Object.values(record).map(literal).join(', ')}\nwhere not exists (select 1 from public.publications where id = ${literal(item.id)} or (lower(btrim(title)) = lower(btrim(${literal(item.title)})) and published_year = ${item.published_year}))\non conflict (id) do nothing;`);
}
statements.push('commit;');
const output = statements.join('\n\n') + '\n';
const target = path.resolve(__dirname, '../supabase/seed.sql');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('seed.sql desatualizado. Execute node scripts/generate-lattes-seed.cjs.');
  console.log('seed.sql sincronizado com o conteúdo Lattes.');
} else {
  fs.writeFileSync(target, output);
  console.log(`seed.sql gerado: ${lattesProjects.length} projetos/trabalhos, ${lattesPublications.length} publicações e perfil.`);
}
